CREATE SCHEMA main;
SET search_path TO main, public;

CREATE TABLE roles (
    role_code smallint PRIMARY KEY,
    role_name text NOT NULL UNIQUE
);

CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text UNIQUE NOT NULL,
    role_code smallint NOT NULL REFERENCES roles
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    access_level integer NOT NULL DEFAULT 0 CHECK (access_level >= 0),
    additional_info text,
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE themes (
    theme_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES themes ON DELETE RESTRICT ON UPDATE RESTRICT,
    theme_name text NOT NULL UNIQUE,
    description text,
    CHECK (parent_id <> theme_id)
);

CREATE TABLE informers (
    informer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    informer_name text NOT NULL,
    informer_type text NOT NULL CHECK (informer_type IN ('person', 'organization')),
    additional_info text
);

CREATE TABLE documents (
    document_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_version bigint REFERENCES documents
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    author bigint NOT NULL REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    moderator bigint REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    date_added timestamptz NOT NULL DEFAULT now(),
    ip_address inet NOT NULL,
    title text NOT NULL,
    additional_info text,
    is_moderated boolean NOT NULL DEFAULT false,
    document_type text NOT NULL,
    content bytea NOT NULL,
    CHECK (parent_version <> document_id)
);

CREATE TABLE favorites (
    user_id bigint REFERENCES users ON DELETE CASCADE ON UPDATE RESTRICT,
    document_id bigint REFERENCES documents ON DELETE CASCADE ON UPDATE RESTRICT,
    date_added timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, document_id)
);

CREATE TABLE view_history (
    view_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES documents
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    user_id bigint NOT NULL REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    date_added timestamptz NOT NULL DEFAULT now(),
    user_ip inet NOT NULL
);

CREATE TABLE safe_ips (
    user_id bigint REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    ip_address inet,
    is_active boolean NOT NULL DEFAULT true,
    date_added timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, ip_address)
);

CREATE TABLE login_history (
    login_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    additional_info text,
    login_ts timestamptz NOT NULL DEFAULT now(),
    login_ip inet NOT NULL
);

CREATE TABLE block_events (
    block_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker bigint REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    blocked bigint NOT NULL REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    is_blocked boolean NOT NULL,
    reason text,
    date_added timestamptz NOT NULL DEFAULT now(),
    CHECK (is_blocked OR (blocker IS NOT NULL))
);

CREATE TABLE comments (
    comment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id bigint REFERENCES comments ON DELETE RESTRICT ON UPDATE RESTRICT,
    document_id bigint NOT NULL REFERENCES documents
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    author_id bigint NOT NULL REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    addressed_id bigint REFERENCES users ON DELETE SET NULL ON UPDATE RESTRICT,
    date_added timestamptz NOT NULL DEFAULT now(),
    content text NOT NULL,
    ip_address inet NOT NULL,
    CHECK (parent_id <> comment_id)
);

CREATE TABLE document_themes (
    theme_id bigint REFERENCES themes ON DELETE RESTRICT ON UPDATE RESTRICT,
    document_id bigint REFERENCES documents ON DELETE CASCADE ON UPDATE RESTRICT,
    PRIMARY KEY (theme_id, document_id)
);

CREATE TABLE document_informers (
    informer_id bigint REFERENCES informers ON DELETE RESTRICT ON UPDATE RESTRICT,
    document_id bigint REFERENCES documents ON DELETE CASCADE ON UPDATE RESTRICT,
    PRIMARY KEY (informer_id, document_id)
);

CREATE TABLE document_coauthors (
    user_id bigint REFERENCES users ON DELETE RESTRICT ON UPDATE RESTRICT,
    document_id bigint REFERENCES documents ON DELETE CASCADE ON UPDATE RESTRICT,
    PRIMARY KEY (user_id, document_id)
);
